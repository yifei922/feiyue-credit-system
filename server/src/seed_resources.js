// 工具函数：为每个 KB 构造稳定的 slug（用于文件命名）
function slug(s) {
  return String(s || '').toLowerCase()
    .replace(/[^a-z0-9\u4e00-\u9fa5]+/g, '-')
    .replace(/(^-|-$)/g, '')
    .slice(0, 60) || crypto.randomBytes(3).toString('hex');
}

async function writeAll(db) {
  if (!fs.existsSync(STUDY_DIR)) fs.mkdirSync(STUDY_DIR, { recursive: true });
  const count = await db.prepare('SELECT COUNT(*) AS c FROM resource').get();
  if (count.c > 0) return; // 已有数据，幂等跳过

  const ins = db.prepare(`INSERT INTO resource
    (grade, subject, title, description, source, type, url, content, tags, view_count, unlock_count, sort_order, created_at)
    VALUES (?, ?, ?, ?, ?, 'article', ?, ?, ?, 0, 0, ?, CURRENT_TIMESTAMP)`);

  let order = 1000;
  for (const k of KB) {
    const filename = `${k.grade}-${k.subject}-${slug(k.title)}.json`;
    const fullpath = path.join(STUDY_DIR, filename);
    const payload = {
      title: k.title,
      description: k.desc,
      sections: k.sections,
      updatedAt: new Date().toISOString(),
    };
    fs.writeFileSync(fullpath, JSON.stringify(payload, null, 2), 'utf8');

    await ins.run(
      k.grade,
      k.subject,
      k.title,
      k.desc,
      SOURCE,
      '/api/mp/resources/file/' + encodeURIComponent(filename),
      JSON.stringify(payload),
      JSON.stringify(k.tags),
      order,
    );
    order -= 1;
  }
  console.log(`[seed_resources] 已播种 ${KB.length} 条通用兴趣类资料到 study-content/`);
}

module.exports = { writeAll, KB };